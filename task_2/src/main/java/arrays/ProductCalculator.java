
package arrays;

// Класс для вычисления произведения элементов массива
public class ProductCalculator {

    // Вычисляет произведение всех элементов массива
    // array — массив чисел, произведение которых нужно вычислить
    // return — результат умножения всех элементов массива
    public static double calculateProduct(double[] array) {

        // Проверяем, что массив существует и содержит элементы
        if (array == null || array.length == 0) {
            throw new ArrayException("Массив не должен быть пустой");
        }

        // Инициализируем произведение единицей
        // Единица не изменяет результат умножения
        double product = 1.0;

        // Перебираем все элементы массива по индексам
        for (int i = 0; i < array.length; i++) {

            // Умножаем текущее произведение на очередной элемент
            product *= array[i];
        }

        // Возвращаем вычисленное произведение
        return product;
    }
}
